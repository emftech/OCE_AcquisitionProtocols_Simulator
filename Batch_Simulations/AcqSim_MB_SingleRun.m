function Results = AcqSim_MB_SingleRun(cfg, W, Number_Meridians, run_tag)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Author: Estéfano Machado Ferrer (batch layer written with Claude Code)
% Date of creation (DD/MM/YY): 20-10-2026
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% AcqSim_MB_SingleRun
%
% Function version of Sampling_Acq_Sim_MB_v4_Ideal_Cylindrical_QH.mlx
% (sections "Definition of Acquisition Vectors" to "Store Metrics"),
% applied to a precomputed wave video W (AcqSim_WaveProp, protocol "MB").
% The same framework functions are called with the same arguments; only
% the plotting/video cells of the live script are replaced by saved
% figures, and an extra annular ROI (needle blanking) is evaluated.
%
% Storage (thesis-like, no saccades):
%   <results>/Multimeridian_MB/Cylindrical/Quasi_Harmonic/<N> Meridians/
%       Quasi_Harmonic_Ideal_<T>us/MB_SimResults_<N>_Meridians_Quasi_Harmonic_Ideal_<T>us.mat
%       MB<N>Mer_Elastogram_<Est>_Masked_R2gt0p7_<T>usExc_QH_Cylindrical.(png|fig)
%       MB<N>Mer_Traces_<T>us.mat  ([N_mer*N_pos x N_t] in acquisition order,
%                                   for the experimental MMB pipeline)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
if nargin < 4, run_tag = ""; end
t_run = tic;

T_excitation = W.T_excitation;
T_us = round(T_excitation*1e6);
Ts_OCT = cfg.Ts_OCT;
hMin = cfg.horizontalMin; hMax = cfg.horizontalMax;
vMin = cfg.verticalMin;   vMax = cfg.verticalMax;
GT_SpeedMap = W.GT_SpeedMap; Bkg_Mask = W.Bkg_Mask; Inc_Mask = W.Inc_Mask; Ann_Mask = W.Ann_Mask;

%% Output folder
exp_type = "Quasi_Harmonic_Ideal";
run_path = fullfile(cfg.results_path, "Multimeridian_MB", "Cylindrical", "Quasi_Harmonic", ...
    sprintf("%d Meridians", Number_Meridians), sprintf("%s_%dus", exp_type, T_us));
if ~isfolder(run_path), mkdir(run_path); end
tagExc = sprintf("%dusExc_QH_Cylindrical", T_us);

%% Acquisition vectors (Multimeridian MB)
nFrames = 1;
nAscans = cfg.MB.nAscans;
nBscans = Number_Meridians;
M_repetitions = cfg.MB.M_repetitions;
nSyncSamples  = cfg.MB.nSyncSamples;
[Exc_Trigger, Acq_Trigger, GalvoX, GalvoY] = AcqVectors_MultimeridianMB(hMin, hMax, vMin, ...
    vMax, nAscans, nBscans, nFrames, ...
    cfg.MB.startDelay_samples, nSyncSamples, cfg.MB.AcqPulseWidth, ...
    cfg.MB.ExcPulseWidth, T_excitation, Ts_OCT, M_repetitions);
close all force;

%% Sampling (ideal)
MotionCase = 'ideal'; AcqFramework = 'MB';
[Spatial_Frames_Generalized_MB, Meridian_Frames_MB, SamplingInfo_MB] = ...
    Sampling_fromAcqVecs_Generalized( ...
    W.Vid, W.x_grid, W.y_grid, W.t_grid, ...
    GalvoX, GalvoY, Acq_Trigger, Exc_Trigger, ...
    nFrames, nAscans, nBscans, T_excitation, Ts_OCT, ...
    MotionCase, AcqFramework, ...
    'SamplesPerSimEnsemble', M_repetitions + nSyncSamples, ...
    'InterpMethod', 'linear', 'ExtrapMethod', 'none', ...
    'TemporalDelay_s', 0, 'MakeDiagnostics', false);
close all force;

%% Near-field blanking BEFORE the estimators (as Main_Processing_SingleExp_MultimerMB_EMF:
% FramesIn(needle,:) = NaN with needle = distance to the tip < NeedleRadius_mm)
R_nf = cfg.NeedleRadius_mm; Src = cfg.Source_mm;
Meridian_Frames_MB_Unblanked = Meridian_Frames_MB;      % exported to the experimental chain (it blanks itself)
x_sf = linspace(hMin, hMax, size(Spatial_Frames_Generalized_MB,1));
y_sf = linspace(vMin, vMax, size(Spatial_Frames_Generalized_MB,2));
[Xsf, Ysf] = ndgrid(x_sf, y_sf);
NearSF = hypot(Xsf - Src(1), Ysf - Src(2)) < R_nf;
Spatial_Frames_MB_Unblanked = Spatial_Frames_Generalized_MB;   % display only (full-field videos)
Spatial_Frames_Generalized_MB(repmat(NearSF, 1, 1, size(Spatial_Frames_Generalized_MB,3))) = NaN;
r_pos  = linspace(-(hMax-hMin)/2, (hMax-hMin)/2, nAscans).';           % AcqVectors_MultimeridianMB geometry
theta  = (0:nBscans-1)*pi/nBscans;
r_acq  = repmat(r_pos, 1, nBscans); r_acq(:, 2:2:end) = flipud(r_acq(:, 2:2:end));   % alternate meridians reversed
Xm = r_acq.*cos(theta); Ym = r_acq.*sin(theta);
NeedleMer = hypot(Xm - Src(1), Ym - Src(2)) < R_nf;                    % [nAscans x nBscans] (acquisition order)
for b = 1:nBscans
    Meridian_Frames_MB(NeedleMer(:,b), :, b) = NaN;
end

%% Interpolation for 2D PG
[WavePropSim_3DMat_MB_Interp, ValidMask_MB, HullMask_MB, InterpOperator_MB] = ...
    Prepare_MB_2DPhaseGradient(Spatial_Frames_Generalized_MB, 'linearDT', false, true);
close all force;
Inc_Mask_ReducedMBGrid = imresize(Inc_Mask, size(WavePropSim_3DMat_MB_Interp, 1:2));
Bkg_Mask_ReducedMBGrid = imresize(Bkg_Mask, size(WavePropSim_3DMat_MB_Interp, 1:2));

%% 2D PG
[Elastogram_MB_2DPG, R2_map_MB_2DPG, Elastogram_Masked_MB_2DPG, ...
 Xcrop_mm_MB_2DPG, Ycrop_mm_MB_2DPG, Complex_Field_Vz_MB_2DPG, ...
 Inc_Mask_Crop_MB_2DPG, Bkg_Mask_Crop_MB_2DPG, Kx_MB_2DPG, Ky_MB_2DPG, Kmag_MB_2DPG] = ...
    PhaseGradient2D_FromSims_v3( ...
        WavePropSim_3DMat_MB_Interp, Inc_Mask_ReducedMBGrid, Bkg_Mask_ReducedMBGrid, ...
        cfg.kernel_size, Ts_OCT, T_excitation, hMin, hMax, vMin, vMax, ...
        cfg.applyTemporalWindow, cfg.clim);
close all force;

%% 2D PG-TV
[Elastogram_MB_2DPG_TV, R2_map_MB_2DPG_TV, Elastogram_Masked_MB_2DPG_TV, ...
 Xcrop_mm_MB_2DPG_TV, Ycrop_mm_MB_2DPG_TV, Complex_Field_Vz_MB_2DPG_TV, ...
 Inc_Mask_Crop_MB_2DPG_TV, Bkg_Mask_Crop_MB_2DPG_TV, Kx_MB_2DPG_TV, Ky_MB_2DPG_TV, Kmag_MB_2DPG_TV, ...
 Kmag_TV_MB_2DPG_TV, Elastogram_raw_MB_2DPG_TV, TVInfo_MB_2DPG_TV] = ...
    PhaseGradient2D_TV_FromSims( ...
        WavePropSim_3DMat_MB_Interp, Inc_Mask_ReducedMBGrid, Bkg_Mask_ReducedMBGrid, ...
        cfg.kernel_size, Ts_OCT, T_excitation, hMin, hMax, vMin, vMax, ...
        cfg.applyTemporalWindow, cfg.clim, ...
        'MuTV', cfg.MuTV, 'TVIterations', cfg.TVIterations, 'TVTau', cfg.TVTau, ...
        'TVSigma', cfg.TVSigma, 'TVTheta', cfg.TVTheta, 'MinK', cfg.MinK, 'MaxK', cfg.MaxK, ...
        'R2Threshold', cfg.R2Threshold, 'DisplayFigures', false, 'Verbose', false);
close all force;

%% 1D PG along meridians
[Elastogram_MB_1DPG, R2_map_MB_1DPG, Elastogram_Masked_MB_1DPG, Xgrid_mm_MB_1DPG, Ygrid_mm_MB_1DPG, ...
 SparseElastogram_MB_1DPG, Inc_Mask_MB_1DPG, KVectorField_MB_1DPG] = ...
    PhaseGradient_1D_AlongMeridians_MBMode_v3( ...
        Meridian_Frames_MB, Inc_Mask, cfg.kernel_size, Ts_OCT, T_excitation, ...
        hMin, hMax, vMin, vMax, 'DisplayResults', false);
close all force;

%% 1D PG-TV along meridians
[Elastogram_MB_1DPG_TV, R2_map_MB_1DPG_TV, Elastogram_Masked_MB_1DPG_TV, ...
 Xgrid_mm_MB_1DPG_TV, Ygrid_mm_MB_1DPG_TV, SparseElastogram_MB_1DPG_TV, ...
 Inc_Mask_MB_1DPG_TV, KVectorField_MB_1DPG_TV] = ...
    PhaseGradient_1D_AlongMeridians_Regularized_TV( ...
        Meridian_Frames_MB, Inc_Mask, cfg.kernel_size, Ts_OCT, T_excitation, ...
        hMin, hMax, vMin, vMax, ...
        'R2_thresh', cfg.R2Threshold, 'DisplayResults', false, ...
        'ApplyTemporalHann', cfg.applyTemporalWindow, 'InterpMethod', 'natural', ...
        'MuTV', cfg.MuTV, 'TVIterations', cfg.TVIterations, 'TVTau', cfg.TVTau, ...
        'TVSigma', cfg.TVSigma, 'TVTheta', cfg.TVTheta, 'TV_UseR2Mask', false, ...
        'TV_R2Threshold', cfg.R2Threshold, 'MinK', cfg.MinK, 'MaxK', cfg.MaxK, 'CLim', cfg.clim);
close all force;

%% Remove the same disk from every map (NearSource), as in the experiments
Elastogram_MB_1DPG          = blankDisk(Elastogram_MB_1DPG,          Xgrid_mm_MB_1DPG,    Ygrid_mm_MB_1DPG,    Src, R_nf);
Elastogram_Masked_MB_1DPG   = blankDisk(Elastogram_Masked_MB_1DPG,   Xgrid_mm_MB_1DPG,    Ygrid_mm_MB_1DPG,    Src, R_nf);
Elastogram_MB_1DPG_TV       = blankDisk(Elastogram_MB_1DPG_TV,       Xgrid_mm_MB_1DPG_TV, Ygrid_mm_MB_1DPG_TV, Src, R_nf);
Elastogram_Masked_MB_1DPG_TV= blankDisk(Elastogram_Masked_MB_1DPG_TV,Xgrid_mm_MB_1DPG_TV, Ygrid_mm_MB_1DPG_TV, Src, R_nf);
Elastogram_MB_2DPG          = blankDisk(Elastogram_MB_2DPG,          Xcrop_mm_MB_2DPG,    Ycrop_mm_MB_2DPG,    Src, R_nf);
Elastogram_Masked_MB_2DPG   = blankDisk(Elastogram_Masked_MB_2DPG,   Xcrop_mm_MB_2DPG,    Ycrop_mm_MB_2DPG,    Src, R_nf);
Elastogram_MB_2DPG_TV       = blankDisk(Elastogram_MB_2DPG_TV,       Xcrop_mm_MB_2DPG_TV, Ycrop_mm_MB_2DPG_TV, Src, R_nf);
Elastogram_Masked_MB_2DPG_TV= blankDisk(Elastogram_Masked_MB_2DPG_TV,Xcrop_mm_MB_2DPG_TV, Ycrop_mm_MB_2DPG_TV, Src, R_nf);

%% Metrics (thesis Ea/Ep) on the thesis background disk and on the annulus
Est = struct();
Est.MB_1DPG    = struct('E', Elastogram_Masked_MB_1DPG,    'x', Xgrid_mm_MB_1DPG,    'y', Ygrid_mm_MB_1DPG);
Est.MB_1DPG_TV = struct('E', Elastogram_Masked_MB_1DPG_TV, 'x', Xgrid_mm_MB_1DPG_TV, 'y', Ygrid_mm_MB_1DPG_TV);
Est.MB_2DPG    = struct('E', Elastogram_Masked_MB_2DPG,    'x', Xcrop_mm_MB_2DPG,    'y', Ycrop_mm_MB_2DPG);
Est.MB_2DPG_TV = struct('E', Elastogram_Masked_MB_2DPG_TV, 'x', Xcrop_mm_MB_2DPG_TV, 'y', Ycrop_mm_MB_2DPG_TV);
Metrics = AcqSim_ComputeMetrics(Est, GT_SpeedMap, Inc_Mask, Bkg_Mask, Ann_Mask, W.Far_Mask);

%% Store (thesis Results struct + batch extras)
Results = struct();
Results.Metadata = struct('exp_type', exp_type, 'protocol_type', "Multimeridian_MB", ...
    'Number_Meridians', Number_Meridians, 'nAscans_per_meridian', nAscans, ...
    'nAscans', nAscans, 'nBscans', nBscans, 'kernel_size', cfg.kernel_size, ...
    'applyTemporalWindow', cfg.applyTemporalWindow, 'clim_limits_2DPG', cfg.clim, ...
    'clim_limits_PGTV', cfg.clim, 'date_saved', string(datetime("now")), 'run_tag', run_tag);
Results.Parameters = struct('c_medium', cfg.c_ref, 'Ts_OCT', Ts_OCT, 'T_excitation', T_excitation, ...
    'f_excitation', 1/T_excitation, 'alpha', cfg.alpha, 'N_pulses', cfg.MB.N_pulses, ...
    'N_excitations', cfg.MB.N_excitations, 'A_Peak', cfg.A_Peak, ...
    'horizontalMin', hMin, 'horizontalMax', hMax, 'verticalMin', vMin, 'verticalMax', vMax, ...
    'nPoints', cfg.nPoints, 'M_repetitions', M_repetitions, 'nSyncSamples', nSyncSamples, ...
    'prop_type', W.prop_type, 'MotionCase', MotionCase, 'AcqFramework', AcqFramework, ...
    'SourceFWHM_mm', cfg.SourceFWHM_mm, 'NeedleExclusion_mm', cfg.NeedleExclusion_mm, ...
    'NearFieldBlanking', struct('Radius_mm', R_nf, 'Source_mm', Src, ...
        'Rule', "samples with distance to the tip < R set to NaN before the estimators; same disk set to NaN on every map"));
Results.Acquisition = struct('GalvoX', GalvoX, 'GalvoY', GalvoY, 'Acq_Trigger', Acq_Trigger, ...
    'Exc_Trigger', Exc_Trigger, 'SamplingInfo_MB', SamplingInfo_MB);
Results.SampledData = struct('Spatial_Frames_Generalized_MB', Spatial_Frames_Generalized_MB, ...
    'Meridian_Frames_MB', Meridian_Frames_MB, 'Meridian_Frames_MB_Unblanked', Meridian_Frames_MB_Unblanked, 'WavePropSim_3DMat_MB_Interp', WavePropSim_3DMat_MB_Interp, ...
    'ValidMask_MB', ValidMask_MB, 'HullMask_MB', HullMask_MB, 'InterpOperator_MB', InterpOperator_MB);
Results.GroundTruth = struct('GT_SpeedMap', GT_SpeedMap, 'Inc_Mask', Inc_Mask, 'Bkg_Mask', Bkg_Mask, ...
    'Ann_Mask', Ann_Mask, 'Inc_Mask_ReducedMBGrid', Inc_Mask_ReducedMBGrid, ...
    'Bkg_Mask_ReducedMBGrid', Bkg_Mask_ReducedMBGrid);
Results.MB_1DPG = struct('Elastogram', Elastogram_MB_1DPG, 'Elastogram_Masked', Elastogram_Masked_MB_1DPG, ...
    'R2_map', R2_map_MB_1DPG, 'Xaxis_mm', Xgrid_mm_MB_1DPG, 'Yaxis_mm', Ygrid_mm_MB_1DPG, ...
    'SparseElastogram', SparseElastogram_MB_1DPG, 'Inc_Mask_Grid', Inc_Mask_MB_1DPG, ...
    'KVectorField', KVectorField_MB_1DPG);
Results.MB_1DPG_TV = struct('Elastogram', Elastogram_MB_1DPG_TV, 'Elastogram_Masked', Elastogram_Masked_MB_1DPG_TV, ...
    'R2_map', R2_map_MB_1DPG_TV, 'Xaxis_mm', Xgrid_mm_MB_1DPG_TV, 'Yaxis_mm', Ygrid_mm_MB_1DPG_TV, ...
    'SparseElastogram', SparseElastogram_MB_1DPG_TV, 'Inc_Mask_Grid', Inc_Mask_MB_1DPG_TV, ...
    'KVectorField', KVectorField_MB_1DPG_TV);
Results.MB_2DPG = struct('Elastogram', Elastogram_MB_2DPG, 'Elastogram_Masked', Elastogram_Masked_MB_2DPG, ...
    'R2_map', R2_map_MB_2DPG, 'Xaxis_mm', Xcrop_mm_MB_2DPG, 'Yaxis_mm', Ycrop_mm_MB_2DPG, ...
    'Complex_Field_Vz', Complex_Field_Vz_MB_2DPG, 'Inc_Mask_Crop', Inc_Mask_Crop_MB_2DPG, ...
    'Bkg_Mask_Crop', Bkg_Mask_Crop_MB_2DPG, 'Kx', Kx_MB_2DPG, 'Ky', Ky_MB_2DPG, 'Kmag', Kmag_MB_2DPG);
Results.MB_2DPG_TV = struct('Elastogram', Elastogram_MB_2DPG_TV, 'Elastogram_Masked', Elastogram_Masked_MB_2DPG_TV, ...
    'Elastogram_raw', Elastogram_raw_MB_2DPG_TV, 'R2_map', R2_map_MB_2DPG_TV, ...
    'Xaxis_mm', Xcrop_mm_MB_2DPG_TV, 'Yaxis_mm', Ycrop_mm_MB_2DPG_TV, ...
    'Complex_Field_Vz', Complex_Field_Vz_MB_2DPG_TV, 'Inc_Mask_Crop', Inc_Mask_Crop_MB_2DPG_TV, ...
    'Bkg_Mask_Crop', Bkg_Mask_Crop_MB_2DPG_TV, 'Kx', Kx_MB_2DPG_TV, 'Ky', Ky_MB_2DPG_TV, ...
    'Kmag_raw', Kmag_MB_2DPG_TV, 'Kmag_TV', Kmag_TV_MB_2DPG_TV, 'TVInfo', TVInfo_MB_2DPG_TV);
fn = fieldnames(Metrics);
for k = 1:numel(fn)
    Results.(fn{k}).AccuracyError  = Metrics.(fn{k}).AccuracyError;
    Results.(fn{k}).PrecisionError = Metrics.(fn{k}).PrecisionError;
    Results.(fn{k}).Annulus        = Metrics.(fn{k}).Annulus;
    Results.(fn{k}).FarField       = Metrics.(fn{k}).FarField;
end
Results.OG_WaveProp = W.OG;
Results.SummaryTable = AcqSim_SummaryTable(Metrics);

results_filename = sprintf("MB_SimResults_%d_Meridians_%s_%dus.mat", Number_Meridians, exp_type, T_us);
Results.Metadata.results_filename = results_filename;
Results.Metadata.results_fullpath = fullfile(run_path, results_filename);
save(fullfile(run_path, results_filename), "Results", "-v7.3");

%% Elastogram figures (thesis naming)
names = {'MB_1DPG','1DPG'; 'MB_1DPG_TV','1DPG_TV'; 'MB_2DPG','2DPG'; 'MB_2DPG_TV','2DPG_TV'};
for k = 1:size(names,1)
    e = Est.(names{k,1});
    f = sprintf("MB%dMer_Elastogram_%s_Masked_R2gt0p7_%s", Number_Meridians, names{k,2}, tagExc);
    AcqSim_SaveElastogram(e.E, e.x, e.y, cfg.clim, ...
        {sprintf('MB %d meridians - %s - %d \\mus', Number_Meridians, strrep(names{k,2},'_','-'), T_us), ...
         sprintf('mean %.2f m/s (annulus r \\geq %.1f mm)', Metrics.(names{k,1}).Annulus.mean, cfg.NeedleExclusion_mm)}, ...
        fullfile(run_path, f), Src);
end

%% Videos and S-T map shown in the live script
xg = linspace(hMin, hMax, size(Spatial_Frames_Generalized_MB,1));
yg = linspace(vMin, vMax, size(Spatial_Frames_Generalized_MB,2));
vopt = struct('Transpose', true, 'FrameStep', 3, 'FrameRate', 30, 'dt_s', 3*Ts_OCT);
AcqSim_WriteVideo(Spatial_Frames_MB_Unblanked, xg, yg, ...
    sprintf('Sampled frames - Multimeridian MB (%d meridians) - %d \\mus', Number_Meridians, T_us), ...
    fullfile(run_path, sprintf("SampledFrames_%dMeridians_%s", Number_Meridians, tagExc)), setfield(vopt, 'NaNMask', NearSF)); %#ok<SFLD>
xi = linspace(hMin, hMax, size(WavePropSim_3DMat_MB_Interp,1));
yi = linspace(vMin, vMax, size(WavePropSim_3DMat_MB_Interp,2));
[Xi, Yi] = ndgrid(xi, yi);
NearI = hypot(Xi - Src(1), Yi - Src(2)) < R_nf;                         % gray disk after interpolation
% Cropped video: interpolation of the blanked samples (what the 2D PG saw) with the disk in gray.
% Full video: interpolation of the unblanked samples (display only), same colour limits.
[InterpFull] = Prepare_MB_2DPhaseGradient(Spatial_Frames_MB_Unblanked, 'linearDT', false, true); close all force;
CropVid = WavePropSim_3DMat_MB_Interp; CropVid(repmat(NearI, 1, 1, size(CropVid,3))) = NaN;
a_ = abs(CropVid(isfinite(CropVid))); limI = prctile(a_, 97);
AcqSim_WriteVideo(CropVid, xi, yi, ...
    sprintf('Interpolated frames for 2D PG - %d meridians - %d \\mus (r < %.2f mm gray)', Number_Meridians, T_us, R_nf), ...
    fullfile(run_path, sprintf("InterpFrames_%dMeridians_%s", Number_Meridians, tagExc)), vopt);
AcqSim_WriteVideo(InterpFull, xi, yi, ...
    sprintf('Interpolated frames - %d meridians - %d \\mus - full field (near field saturated)', Number_Meridians, T_us), ...
    fullfile(run_path, sprintf("InterpFrames_%dMeridians_%s_Full", Number_Meridians, tagExc)), setfield(vopt, 'CLim', limI)); %#ok<SFLD>
clear CropVid InterpFull;
% Space-time map, meridians concatenated (MMB_PlotSpaceTime: needle band in gray)
[nA_, nT_, nB_] = size(Meridian_Frames_MB);
ST = reshape(permute(Meridian_Frames_MB, [1 3 2]), nA_*nB_, nT_);
ST = ST - mean(ST, 2, 'omitnan');
STfull = reshape(permute(Meridian_Frames_MB_Unblanked, [1 3 2]), nA_*nB_, nT_);
STfull = STfull - mean(STfull, 2, 'omitnan');
L_mer = hMax - hMin;
f = MMB_PlotSpaceTime({ST, STfull}, {sprintf('Simulated QH field, %d meridians, %d \\mus (near field r < %.2f mm blanked)', nB_, T_us, R_nf), ...
    'Full field, same colour limits (near field saturated)'}, ...
    ((1:nA_*nB_) - 0.5)*L_mer/nA_, (0:nT_-1)*Ts_OCT*1e3, L_mer, ...
    sprintf('Space-time map - Multimeridian MB simulation (FWHM %.2f mm)', cfg.SourceFWHM_mm), 'CLimPct', 97);
set(f, 'Visible', 'off');
exportgraphics(f, fullfile(run_path, sprintf("Meridian_ST_Frames_%dMeridians_%s.png", Number_Meridians, tagExc)), 'Resolution', 150);
savefig(f, fullfile(run_path, sprintf("Meridian_ST_Frames_%dMeridians_%s.fig", Number_Meridians, tagExc)));
close(f);

%% Traces in acquisition order for the experimental MMB pipeline
[nA, nT, nB] = size(Meridian_Frames_MB);
Traces = reshape(permute(Meridian_Frames_MB_Unblanked, [1 3 2]), nA*nB, nT);  % NOT blanked  % row = (b-1)*N_pos + position
Info = struct('fs', 1/Ts_OCT, 'f_exc', 1/T_excitation, 'L_mm', hMax - hMin, 'N_pos', nA, ...
    'N_mer', nB, 'Source_mm', [0 0], 'SourceFWHM_mm', cfg.SourceFWHM_mm, 'c_ref', cfg.c_ref, ...
    'ReverseAlternate', "as generated by AcqVectors_MultimeridianMB (traces kept in acquisition order)", ...
    'Units', "k-Wave acoustic pressure (arbitrary units, linear in the particle velocity of the cylindrical wave)", ...
    'SignConvention', "u(t) as simulated; global sign irrelevant for PG/DF", ...
    'Layout', "Traces(row,:) with row = (meridian-1)*N_pos + position_in_acquisition_order", ...
    'GalvoX_mm', GalvoX, 'GalvoY_mm', GalvoY, 'Acq_Trigger', Acq_Trigger);
save(fullfile(run_path, sprintf("MB%dMer_Traces_%dus.mat", Number_Meridians, T_us)), "Traces", "Info", "-v7.3");

fprintf('[MB] %2d meridians @ %d us done in %.1f s -> %s\n', Number_Meridians, T_us, toc(t_run), run_path);
end

%% ------------------------------------------------------------------------
function E = blankDisk(E, x_mm, y_mm, Src, R)
% NaN the disk |r - Src| < R on a map whose axes are x_mm / y_mm (works for
% [Ny x Nx] and [Nx x Ny] maps; the disk is symmetric for a centred source).
if isempty(E), return; end
if isequal(size(E), [numel(y_mm) numel(x_mm)])
    [X, Y] = meshgrid(x_mm, y_mm);
else
    [X, Y] = ndgrid(x_mm, y_mm);
end
E(hypot(X - Src(1), Y - Src(2)) < R) = NaN;
end
